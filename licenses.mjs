import { readFile, readdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const lock=JSON.parse(await readFile('package-lock.json','utf8'));
const groups=new Map();
const rows=[];
// saxes 6.0.0 omits LICENSE from its npm tarball. Preserve both upstream ISC
// copyright notices with their shared permission/disclaimer, verified at:
// https://github.com/lddubeau/saxes/blob/v6.0.0/LICENSE
const saxesLicense=`The ISC License

Copyright (c) Contributors
Copyright (c) Isaac Z. Schlueter and Contributors

Permission to use, copy, modify, and/or distribute this software for any
purpose with or without fee is hereby granted, provided that the above
copyright notice and this permission notice appear in all copies.
THE SOFTWARE IS PROVIDED "AS IS" AND THE AUTHOR DISCLAIMS ALL WARRANTIES
WITH REGARD TO THIS SOFTWARE INCLUDING ALL IMPLIED WARRANTIES OF
MERCHANTABILITY AND FITNESS. IN NO EVENT SHALL THE AUTHOR BE LIABLE FOR
ANY SPECIAL, DIRECT, INDIRECT, OR CONSEQUENTIAL DAMAGES OR ANY DAMAGES
WHATSOEVER RESULTING FROM LOSS OF USE, DATA OR PROFITS, WHETHER IN AN
ACTION OF CONTRACT, NEGLIGENCE OR OTHER TORTIOUS ACTION, ARISING OUT OF OR
IN CONNECTION WITH THE USE OR PERFORMANCE OF THIS SOFTWARE.
`;
for(const [directory,entry] of Object.entries(lock.packages).sort(([a],[b])=>a.localeCompare(b))){
  if(!directory||entry.dev)continue;
  const pkg=JSON.parse(await readFile(`${directory}/package.json`,'utf8'));
  if(pkg.version!==entry.version)throw new Error(`Installed version differs from lockfile: ${pkg.name}`);
  const names=(await readdir(directory)).filter(name=>/^(?:licen[sc]e|notice|copying)(?:\.|$)/i.test(name)).sort();
  const texts=[];
  for(const name of names)texts.push(await readFile(`${directory}/${name}`,'utf8'));
  if(!texts.length){
    if(pkg.name==='saxes'&&pkg.version==='6.0.0'&&entry.license==='ISC')texts.push(saxesLicense);
    else if(['@aws-sdk/credential-provider-http','@aws-sdk/credential-provider-login','@aws-sdk/nested-clients'].includes(pkg.name)&&entry.license==='Apache-2.0'){
      // These AWS monorepo packages omit their license file; use the license
      // shipped by the same repository's S3 client, keeping NOTICE if supplied.
      texts.push(await readFile('node_modules/@aws-sdk/client-s3/LICENSE','utf8'));
    }else throw new Error(`Missing license text: ${pkg.name}. Review upstream before distributing.`);
  }
  const text=texts.join('\n\n').trim(),digest=createHash('sha256').update(text).digest('hex');
  let group=groups.get(digest);
  if(!group){group={id:groups.size+1,text,packages:[]};groups.set(digest,group);}
  group.packages.push(`${pkg.name}@${pkg.version}`);
  rows.push(`| ${pkg.name} | ${pkg.version} | ${entry.license??pkg.license??'See text'} | [${group.id}](#notice-${group.id}) |`);
}
const output=[
  '# Third-party notices',
  '',
  'Generated by `npm run licenses` from installed, lockfile-pinned runtime dependencies. Some editor packages are provided by Obsidian rather than bundled. Pictether source is MIT; these components retain their own licenses. Development tools are not shipped in the plugin ZIP.',
  '',
  'The AVIF test fixture attribution and upstream notices are retained in `tests/image-fixtures.ts`; test fixtures are not included in the plugin ZIP. Obsidian, Electron, Node.js and the host PDF.js viewer are provided by the host application.',
  '',
  'Saxes upstream ISC notices: https://github.com/lddubeau/saxes/blob/v6.0.0/LICENSE. The retired historical String.fromCodePoint implementation discussed there is not part of saxes 6.0.0.',
  '',
  '| Package | Version | License | Text |',
  '| --- | --- | --- | --- |',
  ...rows,
  ...[...groups.values()].flatMap(group=>['',`## Notice ${group.id}`,'',group.packages.join(', '),'','```text',group.text,'```'])
].join('\n')+'\n';
await writeFile('THIRD_PARTY_NOTICES.md',output);
console.log(`Collected ${rows.length} runtime dependency notices (${groups.size} distinct texts).`);
